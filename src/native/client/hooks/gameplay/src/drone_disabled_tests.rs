unsafe extern "thiscall" fn hp0_update_hook(state:usize,dt:f32) {
    let native:unsafe extern "thiscall" fn(usize,f32)=std::mem::transmute(HP0_NATIVE_UPDATE.with(Cell::get));
    let accepted=crate::drone_control::runtime::test_advance_disabled(
        HP0_HUD.with(Cell::get),state,HP0_LAYOUT.with(|s|s.get().unwrap()),C7_HUD_VT.with(Cell::get),
        |s,mode|c7_present(s,mode),|s|native(s,dt));
    if !accepted {native(state,dt);}
}
unsafe extern "thiscall" fn hp0_cancel(manager: usize, id: u32) {
    c12_cancel_animation(manager,id);
    if HP0_REENTER.with(|x|x.replace(false)) {
        let update: unsafe extern "thiscall" fn(usize,f32)=std::mem::transmute(HP0_UPDATE_ENTRY.with(Cell::get));
        update(HP0_STATE.with(Cell::get),1.0/60.0);
    }
}


