//! Reject local Spy sliding cover proposals unless the bound cover action is held.
//! D5E070 is shared by checked and unchecked local transitions. Manager-level
//! replication/default restoration (EF3300/F004C0 -> EF31B0) is not hooked.
//! No input binding, collision flag, timer, active manager or animation is changed.

use std::ffi::c_void;
use retour::static_detour;
use tracing::{error, info};

const QUEUE_STATE: usize = 0x00D5_E070;
const RETURN_STATE: usize = 0x00E8_7AA0;
const SLIDE_VTABLE: u32 = 0x02BE_6D14;
const COVER_NAV_VTABLE: u32 = 0x02BC_1824;
const COVER_SIMPLE_VTABLE: u32 = 0x02BC_1A74;

static_detour! {
    // D5E070: ECX=pawn; state, params, priority on stack; void; ret 0C.
    static QueueStateHook: unsafe extern "thiscall" fn(*mut c_void, *mut c_void, *const u8, i32);
}

fn word(base: *const u8, offset: usize) -> Option<u32> {
    unsafe { crate::equipment_native::word(base as usize, offset) }
}

fn pointer(base: *const u8, offset: usize) -> Option<*const u8> {
    word(base, offset).filter(|v| *v != 0).map(|v| v as usize as *const u8)
}

// Semantic IDs come from E9F039/E9F05B and 15D5634..15D5680, not a key code.
const COVER_PRESS: u32 = 0x1a;
const COVER_TOGGLE: u32 = 0x1c;
const INPUT_ACTIONS: usize = 0x0313_3308;
const ACTION_COUNT: u32 = 187;
const BUTTON_HELD: usize = 0x00E7_1E60;

fn cover_action_held(controller: *const u8) -> bool {
    let Some(mapping) = pointer(controller, 0x550) else { return false; };
    let Some(count) = word(mapping, 0x2c).filter(|n| (1..=256).contains(n)) else { return false; };
    let Some(entries) = pointer(mapping, 0x28) else { return false; };
    let Some(input) = pointer(controller, 0x548) else { return false; };
    if word(input, 0x3c).is_none() || word(input, 0x40).is_none() {
        return false;
    }
    // E9EC60 dispatch accepts every matching four-byte mapping entry. The
    // current mapping is read on demand: rebinding/device changes are not cached.
    for index in 0..count as usize {
        let Some(entry) = word(entries, index * 4) else { return false; };
        if !matches!(entry & 0xff, COVER_PRESS | COVER_TOGGLE) { continue; }
        let delivered = (entry >> 8) & 0xff;
        if delivered == 0 || delivered >= ACTION_COUNT { continue; }
        let descriptor = (INPUT_ACTIONS + delivered as usize * 16) as *const u8;
        if word(descriptor, 0) != Some(delivered) { continue; }
        let Some(button) = word(descriptor, 4).filter(|n| *n < 63) else { continue; };
        // The bound native query is read-only, takes ECX=controller, button on
        // stack and returns int (ret 4). Do not substitute its mask semantics or
        // the sticky pawn+948 detector bit (SlideEnter sets that bit itself).
        let held: unsafe extern "thiscall" fn(*const u8, u32) -> i32 =
            unsafe { std::mem::transmute(BUTTON_HELD) };
        if unsafe { held(controller, button) } != 0 { return true; }
    }
    false
}

fn should_reject(pawn: *const u8, state: *const u8) -> bool {
    // Unrelated state proposals take the shortest path. Do not inspect another
    // role's state managers or keep object pointers after this synchronous call.
    if !matches!(word(state, 0), Some(COVER_NAV_VTABLE | COVER_SIMPLE_VTABLE))
        || pointer(state, 0x48) != Some(pawn)
    {
        return false;
    }
    let now = unsafe { super::GetTickCount64() };
    let local = super::LOCAL_PAWN_OBSERVATION.with(|slot| {
        slot.get().is_some_and(|(id, at)| id == pawn as usize && now >= at && now - at <= 250)
    });
    if !local || super::pawn_roles(word(pawn, 0x374)) != (true, false) {
        return false;
    }
    let Some(controller) = pointer(pawn, 0x938) else { return false; };
    if pointer(controller, 0x520) != Some(pawn) {
        return false;
    }
    let Some(world) = pointer(pawn, 0x144) else { return false; };
    if pointer(controller, 0x144) != Some(world) || word(pawn, 0x16ec).is_none() {
        return false;
    }
    // D873F0's three state layers. B24==7 is deliberately NOT used: the real
    // Slide exit can leave that mode behind after its state has ended.
    let sliding = (0..3).any(|layer| {
        pointer(pawn, 0x16e0 + layer * 4)
            .and_then(|manager| pointer(manager, 0x28))
            .is_some_and(|active| {
                word(active, 0) == Some(SLIDE_VTABLE)
                    && pointer(active, 0x48) == Some(pawn)
            })
    });
    sliding && !cover_action_held(controller)
}

fn queue_state_with(
    pawn: *mut c_void,
    state: *mut c_void,
    params: *const u8,
    priority: i32,
    original: impl FnOnce(*mut c_void, *mut c_void, *const u8, i32),
    cleanup: impl FnOnce(*mut c_void),
    release: impl FnOnce(*mut c_void, *mut c_void),
) {
    if !should_reject(pawn.cast(), state.cast()) {
        original(pawn, state, params, priority);
        return;
    }
    // Exact D5E0F1 ordering: cleanup proposed state, THEN read the pawn's pool.
    // This native synchronous callback contract keeps pawn valid across cleanup;
    // do not snapshot pool before cleanup or access state after release.
    cleanup(state);
    let pool = unsafe { pawn.cast::<u8>().add(0x16ec).cast::<u32>().read_unaligned() };
    if pool != 0 {
        release(pool as usize as *mut c_void, state);
    }
}

fn queue_state(pawn: *mut c_void, state: *mut c_void, params: *const u8, priority: i32) {
    queue_state_with(
        pawn, state, params, priority,
        |p, s, a, n| unsafe { QueueStateHook.call(p, s, a, n) },
        |s| unsafe {
            // Exact class vtables/cleanup binding are verified before install.
            let table = s.cast::<u32>().read_unaligned() as usize;
            let address = ((table + 0x6c) as *const u32).read_unaligned() as usize;
            let cleanup: unsafe extern "thiscall" fn(*mut c_void) = std::mem::transmute(address);
            cleanup(s);
        },
        |pool, s| unsafe {
            // E87AA0 takes ECX=pool and state on stack, returns void (ret 4).
            let release: unsafe extern "thiscall" fn(*mut c_void, *mut c_void) = std::mem::transmute(RETURN_STATE);
            release(pool, s);
        },
    );
}

