pub(super) unsafe fn init() {
    // The parent already admitted the supported retail DX11 image. This hook
    // has its own binding/install result; failure does not disable other rules.
    if QueueStateHook.is_enabled() { return; }
    if !signatures_match() {
        error!("SCBL_SPY_SLIDE_COVER enabled=false reason=signature-mismatch");
        return;
    }
    match QueueStateHook.initialize(std::mem::transmute(QUEUE_STATE), queue_state)
        .and_then(|hook| hook.enable())
    {
        Ok(()) => info!("SCBL_SPY_SLIDE_COVER enabled=true scope=local-spy-live-slide cover=bound-action-held queue=native-owned-reject"),
        Err(reason) => error!("SCBL_SPY_SLIDE_COVER enabled=false reason={reason:?}"),
    }
}

pub(super) unsafe fn deinit() {
    if QueueStateHook.is_enabled() {
        if let Err(reason) = QueueStateHook.disable() {
            error!("SCBL_SPY_SLIDE_COVER disable_failed=true reason={reason:?}");
        }
    }
}
